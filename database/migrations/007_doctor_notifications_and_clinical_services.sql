ALTER TABLE thong_bao
  ADD COLUMN IF NOT EXISTS duong_dan VARCHAR(500),
  ADD COLUMN IF NOT EXISTS ma_su_kien VARCHAR(180);

CREATE UNIQUE INDEX IF NOT EXISTS uq_thong_bao_ma_su_kien
  ON thong_bao (ma_su_kien);

CREATE INDEX IF NOT EXISTS idx_thong_bao_tai_khoan_chua_doc
  ON thong_bao (id_tai_khoan, ngay_tao DESC)
  WHERE thoi_gian_doc IS NULL;

ALTER TABLE phieu_kham
  ADD COLUMN IF NOT EXISTS thoi_gian_xuat_hien TEXT,
  ADD COLUMN IF NOT EXISTS dien_tien_benh TEXT,
  ADD COLUMN IF NOT EXISTS dien_tien_sau_dieu_tri TEXT,
  ADD COLUMN IF NOT EXISTS tu_van_cham_soc TEXT,
  ADD COLUMN IF NOT EXISTS khong_can_can_lam_sang BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS khong_ke_don BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS danh_muc_dich_vu_lam_sang (
  id_dich_vu BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ma_dich_vu VARCHAR(50) NOT NULL UNIQUE,
  ten_dich_vu VARCHAR(255) NOT NULL,
  nhom_dich_vu VARCHAR(100),
  don_vi_thuc_hien VARCHAR(255),
  don_gia NUMERIC(12,2) NOT NULL DEFAULT 0,
  dang_hoat_dong BOOLEAN NOT NULL DEFAULT TRUE,
  ngay_tao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_dich_vu_lam_sang_don_gia CHECK (don_gia >= 0)
);

CREATE TABLE IF NOT EXISTS chi_dinh_dich_vu_lam_sang (
  id_chi_dinh BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lich_hen BIGINT NOT NULL,
  id_dich_vu BIGINT NOT NULL,
  id_bac_si_chi_dinh BIGINT NOT NULL,
  muc_dich TEXT,
  muc_uu_tien VARCHAR(30) NOT NULL DEFAULT 'Thuong',
  trang_thai VARCHAR(40) NOT NULL DEFAULT 'Cho thuc hien',
  ngay_chi_dinh TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_chi_dinh_lam_sang_lich_hen FOREIGN KEY (id_lich_hen)
    REFERENCES lich_hen(id_lich_hen) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_chi_dinh_lam_sang_dich_vu FOREIGN KEY (id_dich_vu)
    REFERENCES danh_muc_dich_vu_lam_sang(id_dich_vu) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_chi_dinh_lam_sang_bac_si FOREIGN KEY (id_bac_si_chi_dinh)
    REFERENCES bac_si(id_bac_si) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT uq_chi_dinh_lam_sang UNIQUE (id_lich_hen, id_dich_vu),
  CONSTRAINT chk_chi_dinh_lam_sang_uu_tien CHECK (muc_uu_tien IN ('Thuong', 'Khan')),
  CONSTRAINT chk_chi_dinh_lam_sang_trang_thai CHECK (trang_thai IN ('Cho thuc hien', 'Dang thuc hien', 'Da co ket qua', 'Da xem ket qua', 'Huy'))
);

CREATE TABLE IF NOT EXISTS ket_qua_dich_vu_lam_sang (
  id_ket_qua BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_chi_dinh BIGINT NOT NULL UNIQUE,
  ket_qua TEXT NOT NULL,
  ket_luan TEXT,
  tep_dinh_kem TEXT,
  nguoi_tra_ket_qua UUID,
  thoi_gian_tra_ket_qua TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ket_qua_lam_sang_chi_dinh FOREIGN KEY (id_chi_dinh)
    REFERENCES chi_dinh_dich_vu_lam_sang(id_chi_dinh) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_ket_qua_lam_sang_nguoi_tra FOREIGN KEY (nguoi_tra_ket_qua)
    REFERENCES tai_khoan(id_tai_khoan) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_chi_dinh_lam_sang_lich_hen
  ON chi_dinh_dich_vu_lam_sang (id_lich_hen, ngay_chi_dinh);
